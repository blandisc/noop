// https://www.iana.org/time-zones). `zone.tab` lists, per zone, a representative
// point in ISO 6709 form (`±DDMM±DDDMM` / `±DDMMSS±DDDMMSS`); we convert each to
// decimal degrees rounded to 0.01° (~1 km, far finer than this module needs).
// `zone.tab` carries the same coordinate column as `zone1970.tab`, so it serves
// as the "tabla derivada compacta" the requirement (FER-133) allows — keeping the
// package pure (no bundled resource to load, no parser at the BLE/IO layer).
